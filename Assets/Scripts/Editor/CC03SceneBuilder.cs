        static Sprite CreatePixelSprite(string name, int width, int height, Func<int, int, Color> pixel, float pixelsPerUnit)
        {
            string texturePath = ArtPath + "/" + name + "_texture.asset";
            string spritePath = ArtPath + "/" + name + ".asset";
            Texture2D texture = AssetDatabase.LoadAssetAtPath<Texture2D>(texturePath);
            if (texture == null)
            {
                texture = new Texture2D(width, height, TextureFormat.RGBA32, false);
                texture.name = name + " texture";
                texture.filterMode = FilterMode.Point;
                texture.wrapMode = TextureWrapMode.Clamp;
                AssetDatabase.CreateAsset(texture, texturePath);
            }
            var pixels = new Color[width * height];
            for (int y = 0; y < height; y++)
                for (int x = 0; x < width; x++) pixels[y * width + x] = pixel(x, y);
            texture.SetPixels(pixels);
            texture.Apply();
            EditorUtility.SetDirty(texture);

            Sprite sprite = AssetDatabase.LoadAssetAtPath<Sprite>(spritePath);
            if (sprite == null)
            {
                sprite = Sprite.Create(texture, new Rect(0, 0, width, height), new Vector2(0.5f, 0.5f), pixelsPerUnit, 0, SpriteMeshType.FullRect);
                sprite.name = name;
                AssetDatabase.CreateAsset(sprite, spritePath);
            }
            return sprite;
        }

        static AudioClip CreateWaveAsset(string fileName, float seconds, Func<float, float> sample)
        {
            string path = AudioPath + "/" + fileName;
            int count = Mathf.CeilToInt(seconds * SampleRate);
            int dataBytes = count * 2;
            using (var stream = new FileStream(path, FileMode.Create, FileAccess.Write))
            using (var writer = new BinaryWriter(stream))
            {
                writer.Write(new[] { 'R', 'I', 'F', 'F' });
                writer.Write(36 + dataBytes);
                writer.Write(new[] { 'W', 'A', 'V', 'E' });
                writer.Write(new[] { 'f', 'm', 't', ' ' });
                writer.Write(16);
                writer.Write((short)1);
                writer.Write((short)1);
                writer.Write(SampleRate);
                writer.Write(SampleRate * 2);
                writer.Write((short)2);
                writer.Write((short)16);
                writer.Write(new[] { 'd', 'a', 't', 'a' });
                writer.Write(dataBytes);
                for (int i = 0; i < count; i++)
                    writer.Write((short)Mathf.RoundToInt(Mathf.Clamp(sample(i / (float)SampleRate), -1f, 1f) * 32767f));
            }
            AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceUpdate);
            AudioImporter importer = AssetImporter.GetAtPath(path) as AudioImporter;
            if (importer != null)
            {
                AudioImporterSampleSettings settings = importer.defaultSampleSettings;
                settings.loadType = AudioClipLoadType.DecompressOnLoad;
                settings.compressionFormat = AudioCompressionFormat.PCM;
                importer.defaultSampleSettings = settings;
                importer.SaveAndReimport();
            }
            return AssetDatabase.LoadAssetAtPath<AudioClip>(path);
        }

        static float GalleryAmbientSample(float t)
        {
            return 0.013f * Mathf.Sin(2f * Mathf.PI * 58f * t) +
                   0.005f * Mathf.Sin(2f * Mathf.PI * 116f * t + 0.3f) +
                   0.0025f * (Mathf.PerlinNoise(t * 5f, 0.41f) - 0.5f);
        }

        static float GalleryMusicSample(float t)
        {
            float result = 0f;
            float[] starts = { 0.28f, 1.24f, 2.35f, 3.55f, 4.65f, 5.55f, 6.85f, 7.55f, 8.22f };
            float[] notes = { 523.25f, 659.25f, 783.99f, 587.33f, 196f, 392f, 523.25f, 659.25f, 783.99f };
            for (int i = 0; i < starts.Length; i++)
            {
                float local = t - starts[i];
                if (local < 0f || local > 0.58f) continue;
                float envelope = Mathf.Exp(-local * 5.2f) * Mathf.Clamp01(local * 70f);
                float gain = i == 4 ? 0.045f : 0.065f;
                result += gain * envelope * (Mathf.Sin(2f * Mathf.PI * notes[i] * local) +
                    0.12f * Mathf.Sin(2f * Mathf.PI * notes[i] * 2.01f * local));
            }
            for (int tap = 0; tap < 3; tap++)
            {
                float local = t - (6.55f + tap * 0.82f);
                if (local >= 0f && local < 0.12f)
                    result += 0.018f * Mathf.Exp(-local * 36f) * Mathf.Sin(2f * Mathf.PI * 2400f * local);
            }
            return result;
        }

        static float MagneticClickSample(float t)
        {
            float envelope = Mathf.Exp(-t * 26f) * Mathf.Clamp01(t * 120f);
            float ring = Mathf.Sin(2f * Mathf.PI * 740f * t) + 0.32f * Mathf.Sin(2f * Mathf.PI * 1480f * t);
            float thump = 0.22f * Mathf.Exp(-t * 48f) * Mathf.Sin(2f * Mathf.PI * 132f * t);
            return 0.24f * envelope * ring + thump;
        }

        static float GalleryStepSample(float t)
        {
            float envelope = Mathf.Exp(-t * 31f) * Mathf.Clamp01(t * 100f);
            float low = Mathf.Sin(2f * Mathf.PI * 92f * t);
            float tile = Mathf.Sin(2f * Mathf.PI * 430f * t) * 0.18f;
            return 0.18f * envelope * (low + tile);
        }

        static float ArchiveDoorSample(float t)
        {
            float latchTime = t - 0.02f;
            float latch = latchTime >= 0f
                ? 0.22f * Mathf.Exp(-latchTime * 32f) * Mathf.Sin(2f * Mathf.PI * 540f * latchTime)
                : 0f;
            float creakTime = t - 0.11f;
            float creak = creakTime >= 0f
                ? 0.055f * Mathf.Sin(2f * Mathf.PI * (110f + 65f * creakTime) * creakTime) *
                  Mathf.Sin(Mathf.PI * Mathf.Clamp01(creakTime / 0.36f))
                : 0f;
            return latch + creak;
        }

        static float DistantWoodSample(float t)
        {
            float first = SoftTap(t, 520f, 0.31f);
            float echo = SoftTap(t - 0.10f, 420f, 0.13f);
            return first + echo;
        }

        static float SoftTap(float t, float frequency, float gain)
        {
            if (t < 0f) return 0f;
            float envelope = Mathf.Exp(-t * 24f) * Mathf.Clamp01(t * 150f);
            return gain * envelope * Mathf.Sin(2f * Mathf.PI * frequency * t);
        }

        static Color DrawGalleryMoonbeam(int x, int y)
        {
            float u = (x + 0.5f) / 144f;
            float v = (y + 0.5f) / 48f;
            float center = 0.46f + (u - 0.5f) * 0.17f;
            float width = 0.12f + 0.035f * Mathf.Sin(u * Mathf.PI);
            float across = Mathf.Clamp01((width - Mathf.Abs(v - center)) / 0.075f);
            float ends = Mathf.SmoothStep(0f, 1f, u / 0.12f) * (1f - Mathf.SmoothStep(0.80f, 1f, u));
            float alpha = across * ends * 0.52f;
            return new Color(0.60f, 0.76f, 1f, alpha);
        }

        static Color DrawArchiveShadow(int x, int y)
        {
            float nx = (x - 47.5f) / 47.5f;
            float ny = (y - 17.5f) / 17.5f;
            float wobble = (Mathf.PerlinNoise(x * 0.19f, y * 0.13f) - 0.5f) * 0.20f;
            float threshold = 0.78f + wobble;
            float shape = nx * nx * 0.8f + ny * ny;
            if (shape > threshold) return new Color(0f, 0f, 0f, 0f);
            float alpha = Mathf.Clamp01((threshold - shape) * 2.2f) * 0.80f;
            return new Color(0.01f, 0.018f, 0.045f, alpha);
        }

        static Color DrawArchiveGlow(int x, int y)
        {
            float dx = (x - 31.5f) / 31.5f;
            float dy = (y - 31.5f) / 31.5f;
            float distance = Mathf.Sqrt(dx * dx + dy * dy);
            float alpha = Mathf.Pow(Mathf.Clamp01(1f - distance), 2.1f) * 0.36f;
            return new Color(0.62f, 0.78f, 1f, alpha);
        }

        static void AddSceneToBuildSettings(string scenePath)
        {
            var scenes = new List<EditorBuildSettingsScene>(EditorBuildSettings.scenes);
            foreach (EditorBuildSettingsScene scene in scenes)
                if (scene.path == scenePath) return;
            scenes.Add(new EditorBuildSettingsScene(scenePath, true));
            EditorBuildSettings.scenes = scenes.ToArray();
        }

        static void SetObject(UnityEngine.Object target, string propertyName, UnityEngine.Object value)
        {
            var serialized = new SerializedObject(target);
            serialized.FindProperty(propertyName).objectReferenceValue = value;
            serialized.ApplyModifiedPropertiesWithoutUndo();
        }

        static void SetObjectArray(UnityEngine.Object target, string propertyName, UnityEngine.Object[] values)
        {
            var serialized = new SerializedObject(target);
            SerializedProperty property = serialized.FindProperty(propertyName);
            property.arraySize = values.Length;
            for (int i = 0; i < values.Length; i++) property.GetArrayElementAtIndex(i).objectReferenceValue = values[i];
            serialized.ApplyModifiedPropertiesWithoutUndo();
        }

        static void SetVector3(UnityEngine.Object target, string propertyName, Vector3 value)
        {
            var serialized = new SerializedObject(target);
            serialized.FindProperty(propertyName).vector3Value = value;
            serialized.ApplyModifiedPropertiesWithoutUndo();
        }
