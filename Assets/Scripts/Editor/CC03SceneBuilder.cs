        static void EnsureFolder(string path)
        {
            if (AssetDatabase.IsValidFolder(path)) return;
            string parent = Path.GetDirectoryName(path).Replace('\\', '/');
            string name = Path.GetFileName(path);
            if (!AssetDatabase.IsValidFolder(parent)) EnsureFolder(parent);
            AssetDatabase.CreateFolder(parent, name);
        }

        static void ImportPixelArt()
        {
            string[] paths =
            {
                ArtPath + "/galeria_moonlit.png",
                ArtPath + "/corredor_acervo.png",
                ArtPath + "/obra_mare_mucuripe.png",
                ArtPath + "/obra_nevoa_baturite.png",
                ArtPath + "/obra_luz_sertao.png"
            };
            foreach (string path in paths)
            {
                TextureImporter importer = AssetImporter.GetAtPath(path) as TextureImporter;
                if (importer == null) continue;
                importer.textureType = TextureImporterType.Sprite;
                importer.spriteImportMode = SpriteImportMode.Single;
                importer.filterMode = FilterMode.Point;
                importer.textureCompression = TextureImporterCompression.Uncompressed;
                importer.alphaIsTransparency = false;
                importer.isReadable = false;
                importer.spritePixelsPerUnit = path.Contains("obra_") ? 3400f : 470.5f;
                importer.SaveAndReimport();
            }
            AssetDatabase.Refresh();
        }

        static Sprite[] LoadFrames(string prefix, int count)
        {
            var frames = new Sprite[count];
            for (int i = 0; i < count; i++)
                frames[i] = AssetDatabase.LoadAssetAtPath<Sprite>(CC01ArtPath + "/" + prefix + "_" + i.ToString("00") + ".asset");
            return frames;
        }

