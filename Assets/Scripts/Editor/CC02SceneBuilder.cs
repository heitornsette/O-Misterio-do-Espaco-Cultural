        static Sprite CreatePixelSprite(string name, int width, int height, Func<int, int, Color> pixel)
        {
            string texturePath = ArtPath + "/" + name + "_texture.asset";
            string spritePath = ArtPath + "/" + name + ".asset";
            Texture2D texture = AssetDatabase.LoadAssetAtPath<Texture2D>(texturePath);
            if (texture == null)
            {
                texture = new Texture2D(width, height, TextureFormat.RGBA32, false);
                texture.name = name + " texture";
                texture.filterMode = FilterMode.Point;
                texture.wrapMode = TextureWrapMode.Clamp;
                AssetDatabase.CreateAsset(texture, texturePath);
            }
            Color[] pixels = new Color[width * height];
            for (int y = 0; y < height; y++)
                for (int x = 0; x < width; x++) pixels[y * width + x] = pixel(x, y);
            texture.SetPixels(pixels);
            texture.Apply();
            EditorUtility.SetDirty(texture);

            Sprite sprite = AssetDatabase.LoadAssetAtPath<Sprite>(spritePath);
            if (sprite == null)
            {
                sprite = Sprite.Create(texture, new Rect(0, 0, width, height), new Vector2(0.5f, 0.5f), 108f, 0, SpriteMeshType.FullRect);
                sprite.name = name;
                AssetDatabase.CreateAsset(sprite, spritePath);
            }
            return sprite;
        }

        static AudioClip CreateWaveAsset(string fileName, float seconds, Func<float, float> sample)
        {
            string path = AudioPath + "/" + fileName;
            int sampleCount = Mathf.CeilToInt(seconds * Rate);
            int dataBytes = sampleCount * 2;
            using (var stream = new FileStream(path, FileMode.Create, FileAccess.Write))
            using (var writer = new BinaryWriter(stream))
            {
                writer.Write(new[] { 'R', 'I', 'F', 'F' });
                writer.Write(36 + dataBytes);
                writer.Write(new[] { 'W', 'A', 'V', 'E' });
                writer.Write(new[] { 'f', 'm', 't', ' ' });
                writer.Write(16);
                writer.Write((short)1);
                writer.Write((short)1);
                writer.Write(Rate);
                writer.Write(Rate * 2);
                writer.Write((short)2);
                writer.Write((short)16);
                writer.Write(new[] { 'd', 'a', 't', 'a' });
                writer.Write(dataBytes);
                for (int i = 0; i < sampleCount; i++)
                {
                    float value = Mathf.Clamp(sample(i / (float)Rate), -1f, 1f);
                    writer.Write((short)Mathf.RoundToInt(value * 32767f));
                }
            }
            AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceUpdate);
            AudioImporter importer = AssetImporter.GetAtPath(path) as AudioImporter;
            if (importer != null)
            {
                AudioImporterSampleSettings settings = importer.defaultSampleSettings;
                settings.loadType = AudioClipLoadType.DecompressOnLoad;
                settings.compressionFormat = AudioCompressionFormat.PCM;
                importer.defaultSampleSettings = settings;
                importer.SaveAndReimport();
            }
            return AssetDatabase.LoadAssetAtPath<AudioClip>(path);
        }

        static float AmbientSample(float t)
        {
            return 0.027f * Mathf.Sin(2f * Mathf.PI * 58f * t) +
                   0.009f * Mathf.Sin(2f * Mathf.PI * 116f * t + 0.4f) +
                   0.004f * (Mathf.PerlinNoise(t * 7f, 0.23f) - 0.5f);
        }

        static float MusicSample(float t)
        {
            float result = 0f;
            float[] starts = { 0.18f, 1.28f, 2.30f, 3.35f, 4.48f, 5.52f, 6.50f, 7.22f };
            float[] notes = { 392f, 523.25f, 392f, 329.63f, 392f, 493.88f, 440f, 392f };
            for (int i = 0; i < starts.Length; i++)
            {
                float local = t - starts[i];
                if (local < 0f || local > 0.62f) continue;
                float envelope = Mathf.Exp(-local * 5.5f) * Mathf.Clamp01(local * 65f);
                result += 0.085f * envelope * (Mathf.Sin(2f * Mathf.PI * notes[i] * local) +
                           0.10f * Mathf.Sin(2f * Mathf.PI * notes[i] * 2.01f * local));
            }
            return result;
        }

        static float WoodenSettleSample(float t)
        {
            float thud = 0f;
            if (t >= 0f)
            {
                float envelope = Mathf.Exp(-t * 9f) * Mathf.Clamp01(t * 90f);
                thud = 0.32f * envelope * (Mathf.Sin(2f * Mathf.PI * 112f * t) + 0.33f * Mathf.Sin(2f * Mathf.PI * 173f * t));
            }
            float clackTime = t - 0.11f;
            float clack = clackTime >= 0f ? 0.11f * Mathf.Exp(-clackTime * 34f) * Mathf.Sin(2f * Mathf.PI * 620f * clackTime) : 0f;
            return thud + clack;
        }

        static float ConfirmationSample(float t)
        {
            return BellNote(t, 0.02f, 659.25f, 0.23f) + BellNote(t, 0.19f, 783.99f, 0.28f) +
                   BellNote(t, 0.37f, 987.77f, 0.31f);
        }

        static float BellNote(float t, float start, float frequency, float length)
        {
            float local = t - start;
            if (local < 0f || local > length) return 0f;
            float envelope = Mathf.Exp(-local * 8f) * Mathf.Clamp01(local * 100f);
            return 0.09f * envelope * (Mathf.Sin(2f * Mathf.PI * frequency * local) +
                   0.13f * Mathf.Sin(2f * Mathf.PI * frequency * 2.7f * local));
        }

        static float LatchSample(float t)
        {
            float envelope = Mathf.Exp(-t * 22f) * Mathf.Clamp01(t * 100f);
            return 0.17f * envelope * (Mathf.Sin(2f * Mathf.PI * 180f * t) + 0.42f * Mathf.Sin(2f * Mathf.PI * 540f * t));
        }

        static float StepSample(float t)
        {
            float envelope = Mathf.Exp(-t * 17f) * Mathf.Clamp01(t * 120f);
            return 0.20f * envelope * (Mathf.Sin(2f * Mathf.PI * 74f * t) + 0.20f * Mathf.Sin(2f * Mathf.PI * 148f * t));
        }

        static void AddSceneToBuildSettings(string path)
        {
            List<EditorBuildSettingsScene> scenes = new List<EditorBuildSettingsScene>(EditorBuildSettings.scenes);
            foreach (EditorBuildSettingsScene scene in scenes)
                if (scene.path == path) return;
            scenes.Add(new EditorBuildSettingsScene(path, true));
            EditorBuildSettings.scenes = scenes.ToArray();
        }

        static void SetObject(UnityEngine.Object target, string propertyName, UnityEngine.Object value)
        {
            SerializedObject serialized = new SerializedObject(target);
            serialized.FindProperty(propertyName).objectReferenceValue = value;
            serialized.ApplyModifiedPropertiesWithoutUndo();
        }

        static void SetObjectArray(UnityEngine.Object target, string propertyName, UnityEngine.Object[] values)
        {
            SerializedObject serialized = new SerializedObject(target);
            SerializedProperty array = serialized.FindProperty(propertyName);
            array.arraySize = values.Length;
            for (int i = 0; i < values.Length; i++) array.GetArrayElementAtIndex(i).objectReferenceValue = values[i];
            serialized.ApplyModifiedPropertiesWithoutUndo();
        }

        static void SetVector3(UnityEngine.Object target, string propertyName, Vector3 value)
        {
            SerializedObject serialized = new SerializedObject(target);
            serialized.FindProperty(propertyName).vector3Value = value;
            serialized.ApplyModifiedPropertiesWithoutUndo();
        }

        static bool InRect(int x, int y, int left, int bottom, int right, int top)
        {
            return x >= left && x <= right && y >= bottom && y <= top;
        }

        static Color DrawPlacementMark(int x, int y)
        {
            int inset = y < 4 ? 10 : (y > 18 ? 16 : (y < 7 ? 6 : 2));
            int left = inset;
            int right = 63 - inset;
            bool border = y == 2 || y == 3 || y == 20 || y == 21 || x == left || x == left + 1 || x == right || x == right - 1;
            if (border && y >= 2 && y <= 21 && x >= left && x <= right)
                return new Color(0.82f, 0.88f, 0.88f, 0.78f);
            if (x > left + 1 && x < right - 1 && y > 3 && y < 20)
                return new Color(0.77f, 0.83f, 0.84f, 0.10f);
            return Color.clear;
        }

        static Color DrawDustPuff(int x, int y)
        {
            bool puff = InRect(x, y, 3, 3, 8, 8) || InRect(x, y, 7, 5, 13, 10) ||
                        InRect(x, y, 10, 2, 15, 7) || InRect(x, y, 5, 8, 10, 11);
            if (!puff) return Color.clear;
            float alpha = 0.20f + 0.35f * ((x + y) % 3) / 2f;
            return new Color(0.78f, 0.80f, 0.79f, alpha);
        }

        static Color DrawFlashlightCone(int x, int y)
        {
            float halfHeight = Mathf.Lerp(1.5f, 20f, x / 111f);
            float distance = Mathf.Abs(y - 23.5f);
            if (distance > halfHeight) return Color.clear;
            float across = 1f - distance / halfHeight;
            float fade = Mathf.Clamp01((1f - x / 111f) * 2.7f + 0.24f);
            return new Color(1f, 0.96f, 0.80f, 0.36f * across * fade);
        }

        static Color DrawStairGlow(int x, int y)
        {
            float dx = (x - 19.5f) / 19.5f;
            float dy = (y - 15.5f) / 15.5f;
            float radius = Mathf.Sqrt(dx * dx + dy * dy);
            float alpha = Mathf.Clamp01(1f - radius) * 0.45f;
            return new Color(0.55f, 0.79f, 1f, alpha);
        }
