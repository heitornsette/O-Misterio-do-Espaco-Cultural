        static Sprite CreateTrimmedSpriteAsset(string spriteName, string fileName)
        {
            string spritePath = ArtPath + "/" + spriteName + "_sprite.asset";
            Sprite existing = AssetDatabase.LoadAssetAtPath<Sprite>(spritePath);
            if (existing != null) return existing;

            Texture2D texture = AssetDatabase.LoadAssetAtPath<Texture2D>(ArtPath + "/" + fileName);
            if (texture == null || !texture.isReadable)
                throw new InvalidOperationException("Could not read sculpture sprite source " + fileName + ".");

            Color32[] pixels = texture.GetPixels32();
            int minX = texture.width, minY = texture.height, maxX = -1, maxY = -1;
            for (int y = 0; y < texture.height; y++)
                for (int x = 0; x < texture.width; x++)
                {
                    if (pixels[y * texture.width + x].a < 32) continue;
                    minX = Mathf.Min(minX, x);
                    minY = Mathf.Min(minY, y);
                    maxX = Mathf.Max(maxX, x);
                    maxY = Mathf.Max(maxY, y);
                }
            if (maxX < minX || maxY < minY)
                throw new InvalidOperationException("Sculpture sprite source is fully transparent: " + fileName + ".");

            var rect = new Rect(minX, minY, maxX - minX + 1, maxY - minY + 1);
            Sprite sprite = Sprite.Create(texture, rect, new Vector2(0.5f, 0f), 180f, 0, SpriteMeshType.Tight);
            sprite.name = spriteName;
            AssetDatabase.CreateAsset(sprite, spritePath);
            return sprite;
        }

